import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

// Extracts only the badge button copy (badge.shared.buttonLine1/buttonLine2/alt)
// from the site app's i18n JSON files, so the shipped bundle stays tiny while
// still tracking the site's Weblate-translated strings as the single source
// of truth, instead of a hand-maintained copy that can silently drift.

const pkgDir = dirname(dirname(fileURLToPath(import.meta.url)));
const siteI18nDir = join(pkgDir, "../../src/i18n");

const { locales } = await import(`${ join(siteI18nDir, "locales.ts") }`);

const badgeTexts = Object.fromEntries(
  locales.map((locale) => {
    const json = JSON.parse(readFileSync(join(siteI18nDir, `${ locale }.json`), "utf8"));
    const { buttonLine1: line1, buttonLine2: line2, alt } = json.badge.shared;
    const missing = Object.entries({ buttonLine1: line1, buttonLine2: line2, alt })
      .filter(([, value]) => !value)
      .map(([key]) => key);
    if (missing.length > 0) {
      throw new Error(
        `Locale "${ locale }" is missing badge.shared.${ missing.join(", badge.shared.") } in src/i18n/${ locale }.json`
      );
    }
    return [locale, { line1, line2, alt }];
  })
);

const out = `// Generated by scripts/generate-badge-texts.mjs — do not edit by hand.
// Source of truth: badge.shared.* in the site app's src/i18n/*.json files.
export const badgeTexts = ${ JSON.stringify(badgeTexts, null, 2) };
`;

writeFileSync(join(pkgDir, "src/badge-texts.generated.ts"), out);
